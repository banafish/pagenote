/// FNV-1a 32 位字符串哈希（跨平台、跨运行结果稳定），
/// 末尾再加一次位混洗，保证对相近字符串（如连续日期）也有均匀分布。
int _fnv1a(String s) {
  var h = 0x811c9dc5;
  for (final c in s.codeUnits) {
    h ^= c;
    h = (h * 0x01000193) & 0xffffffff;
  }
  h ^= h >> 16;
  h = (h * 0x45d9f3b) & 0xffffffff;
  h ^= h >> 16;
  return h & 0x7fffffff;
}

/// 按日期确定性选取当日问题索引（同一天内结果不变，REQ-04.1）。
int promptIndexForDate(String dateKey, [int offset = 0]) =>
    (_fnv1a(dateKey) + offset) % promptLibrary.length;

/// 当日一问文本。
String promptForDate(String dateKey, [int offset = 0]) =>
    promptLibrary[promptIndexForDate(dateKey, offset)];
